<?php

/**
 * 政令指定都市の行政区コード（地図境界データ取得用）
 *
 * キーは市の5桁コード、値は区の5桁コード一覧。
 */
$cities = [
    '01100' => [1, 10],  // 札幌市
    '04100' => [1, 5],   // 仙台市
    '11100' => [1, 10],  // さいたま市
    '12100' => [1, 6],   // 千葉市
    '14100' => [1, 18],  // 横浜市
    '14130' => [31, 37], // 川崎市
    '14150' => [51, 53], // 相模原市
    '15100' => [1, 8],   // 新潟市
    '22100' => [1, 3],   // 静岡市
    '22130' => [31, 37], // 浜松市
    '23100' => [1, 16],  // 名古屋市
    '26100' => [1, 11],  // 京都市
    '27100' => [1, 24],  // 大阪市
    '27140' => [41, 47], // 堺市
    '28100' => [1, 9],   // 神戸市
    '33100' => [1, 4],   // 岡山市
    '34100' => [1, 8],   // 広島市
    '40100' => [1, 7],   // 北九州市
    '40130' => [31, 37], // 福岡市
    '43100' => [1, 5],   // 熊本市
];

$wards = [];

foreach ($cities as $cityCode => [$from, $to]) {
    $prefix = substr($cityCode, 0, 3);

    for ($ward = $from; $ward <= $to; $ward++) {
        $wards[$cityCode][] = $prefix . str_pad((string) $ward, 2, '0', STR_PAD_LEFT);
    }
}

return $wards;
